let currentUiLang = "tr";

function t(key, fallback = "") {
  const dict = I18N_DICT[currentUiLang] || I18N_DICT.tr;
  return dict[key] || I18N_DICT.tr[key] || fallback || key;
}

function applyUiLanguage(langCode) {
  currentUiLang = I18N_DICT[langCode] ? langCode : "tr";
  document.documentElement.setAttribute("lang", currentUiLang);

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const k = el.getAttribute("data-i18n");
    if (k) el.textContent = t(k, el.textContent);
  });
  document.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const k = el.getAttribute("data-i18n-ph");
    if (k) el.setAttribute("placeholder", t(k, el.getAttribute("placeholder") || ""));
  });
  document.querySelectorAll("[data-i18n-tip]").forEach(el => {
    const k = el.getAttribute("data-i18n-tip");
    if (k) el.setAttribute("data-tip", t(k, el.getAttribute("data-tip") || ""));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const k = el.getAttribute("data-i18n-title");
    if (k) el.setAttribute("title", t(k, el.getAttribute("title") || ""));
  });

  // Update UI lang display label in Profile
  const uObj = UI_LANGUAGES.find(x => x.code === currentUiLang);
  const pvu = document.getElementById("prof-val-ui-lang");
  if (pvu && uObj) pvu.textContent = uObj.label;

  const quitBtn = document.getElementById("btn-app-quit");
  if (quitBtn) quitBtn.title = t("quit_title");
}
